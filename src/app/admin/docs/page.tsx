function navLinkClass(active: boolean) {
    return `rounded-lg px-3 py-2 text-sm transition-colors ${
        active
            ? "bg-gray-100 text-gray-900 font-medium"
            : "text-gray-600 hover:bg-gray-50 hover:text-gray-900"
    }`
}

function subnavLinkClass(active: boolean) {
    return `rounded-lg px-3 py-2 text-sm transition-colors ${
        active
            ? "bg-gray-900 text-white font-medium"
            : "text-gray-500 hover:bg-gray-50 hover:text-gray-900"
    }`
}

function buildDocHref(sectionId?: string, topicId?: string) {
    if (!sectionId) return "/admin/docs"
    if (!topicId) return `/admin/docs?section=${sectionId}`
    return `/admin/docs?section=${sectionId}&topic=${topicId}`
}

