export default async function AdminDocsPage({ searchParams }: { searchParams: SearchParams }) {
    const { section = overview.id, topic } = await searchParams
    const activeSection = sections.find((item) => item.id === section) ?? null
    const activeTopic = activeSection?.detailTopics?.find((item) => item.id === topic) ?? null
    const activeTitle = activeTopic?.title ?? activeSection?.title ?? overview.title
    const activeDescription = activeTopic?.summary ?? activeSection?.summary ?? overview.description

    return (
        <div className="py-6">
            <div className="max-w-3xl">
                <h1 className="text-xl font-bold text-gray-900">Документация</h1>
            </div>

            <div className="mt-6 grid gap-6 lg:grid-cols-[260px_minmax(0,1fr)]">
                <aside className="lg:sticky lg:top-16 lg:self-start">
                    <div className="rounded-2xl border border-gray-200 bg-white p-4">
                        <h2 className="text-sm font-semibold text-gray-900">Разделы</h2>
                        <p className="mt-2 text-xs leading-5 text-gray-500">
                            Выберите раздел. У сложных разделов подпункты раскрываются прямо в меню.
                        </p>
                        <nav className="mt-4 flex flex-wrap gap-2 lg:flex-col">
                            <Link href={buildDocHref()} className={navLinkClass(!activeSection)}>
                                {overview.title}
                            </Link>
                            {sections.map((item) => (
                                <div key={item.id} className="flex flex-col gap-1">
                                    <Link
                                        href={buildDocHref(item.id)}
                                        className={navLinkClass(item.id === activeSection?.id)}
                                    >
                                        {item.title}
                                    </Link>

                                    {item.id === activeSection?.id &&
                                        item.detailTopics &&
                                        item.detailTopics.length > 0 && (
                                            <div className="ml-3 flex flex-col gap-1 border-l border-gray-100 pl-3">
                                                <Link
                                                    href={buildDocHref(item.id)}
                                                    className={subnavLinkClass(!activeTopic)}
                                                >
                                                    Общее по разделу
                                                </Link>
                                                {item.detailTopics.map((detailTopic) => (
                                                    <Link
                                                        key={detailTopic.id}
                                                        href={buildDocHref(item.id, detailTopic.id)}
                                                        className={subnavLinkClass(
                                                            detailTopic.id === activeTopic?.id,
                                                        )}
                                                    >
                                                        {detailTopic.title}
                                                    </Link>
                                                ))}
                                            </div>
                                        )}
                                </div>
                            ))}
                        </nav>
                    </div>
                </aside>

                <div className="space-y-4">
                    <div className="rounded-2xl border border-gray-200 bg-gray-50 p-4">
                        <p className="text-xs uppercase tracking-wide text-gray-500">
                            Сейчас открыт раздел
                        </p>
                        <h2 className="mt-1 text-lg font-semibold text-gray-900">{activeTitle}</h2>
                        <p className="mt-2 text-sm leading-6 text-gray-600">{activeDescription}</p>
                    </div>

                    {!activeSection && <OverviewCard />}

                    {activeSection && !activeTopic && <SectionCard {...activeSection} />}

                    {activeSection && activeTopic && (
                        <TopicCard section={activeSection} topic={activeTopic} />
                    )}
                </div>
            </div>
        </div>
    )
}
